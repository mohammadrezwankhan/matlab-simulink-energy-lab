function validate_release_evidence(report, phase, sourceCommit)
%VALIDATE_RELEASE_EVIDENCE Require one complete R2026a phase for an exact commit.
% This pure validator neither executes checks nor reads or writes artifacts.
arguments
    report (1, 1) struct
    phase (1, 1) string
    sourceCommit (1, 1) string
end
textFields = {'schema_version', 'phase', 'matlab_release', ...
    'source_commit', 'source_state'};
requiredFields = [textFields, {'passed', 'complete'}];
assert(all(isfield(report, requiredFields)), 'ReleaseArchive:EvidenceSchema', ...
    'Phase %s evidence is missing required fields.', phase);
for index = 1:numel(textFields)
    value = report.(textFields{index});
    validText = (isstring(value) && isscalar(value) && ~ismissing(value)) || ...
        (ischar(value) && isrow(value));
    assert(validText, 'ReleaseArchive:EvidenceSchema', ...
        'Phase %s evidence field %s must contain scalar text.', ...
        phase, textFields{index});
end
assert(islogical(report.passed) && isscalar(report.passed) && ...
    islogical(report.complete) && isscalar(report.complete), ...
    'ReleaseArchive:EvidenceSchema', ...
    'Phase %s evidence pass/completion flags must be logical scalars.', phase);
assert(string(report.schema_version) == "1.0.0", ...
    'ReleaseArchive:EvidenceSchema', ...
    'Phase %s evidence must use schema 1.0.0.', phase);
assert(string(report.phase) == phase, 'ReleaseArchive:EvidencePhase', ...
    'Expected phase %s evidence, found %s.', phase, report.phase);
assert(string(report.matlab_release) == "R2026a", ...
    'ReleaseArchive:EvidenceRelease', ...
    'Phase %s evidence must be generated by MATLAB R2026a.', phase);
assert(report.passed && report.complete && ...
    string(report.source_commit) == sourceCommit && ...
    string(report.source_state) == "clean", ...
    'ReleaseArchive:Evidence', ...
    'Phase %s must completely pass on this clean commit.', phase);
end
